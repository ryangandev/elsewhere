// Reopening reviewed content: the request review records on a reviewed part, how review shows it,
// the refusals that keep a reopened country from being redrafted as one file, and the API revision
// of a reopened hand-written story. The agent revision of one is tested in agent.test.ts. Every
// test works on a copy of content/en, whose ten countries were converted by hand and reviewed.
import { describe, expect, it } from 'vitest';
import { CountryFile, type Story } from '../../src/content/schema';
import { createContentStore } from '../../src/content/store';
import { readContentTree } from '../../src/content/files';
import { defaultClaimsDir, readClaims } from '../../pipeline/claims/store';
import { parsedCountryFiles, readCountryFile, writeCountryFile } from '../../pipeline/content-tree';
import { assembleCountry, toDraftSources, toDraftStory } from '../../pipeline/generate/assemble';
import { CountryDraft } from '../../pipeline/generate/draft-schema';
import { normalizeUrl } from '../../pipeline/generate/evidence';
import { replaceConflict } from '../../pipeline/generate/replace';
import { overviewSession, storySession } from '../../pipeline/generate/tasks';
import { approve, reopen, requestRevision, ReviewError } from '../../pipeline/review/actions';
import { countrySummary, listing, reopenReport, sentBackText } from '../../pipeline/review/summary';
import { chileDraft } from './fixtures/build-replay';
import { RUN_DATE, runContext, tempContentTree } from './helpers';

// A redraft checks every route against land geometry, which takes a few seconds on a CI runner.
const REDRAFT_TIMEOUT_MS = 30_000;
const NOTES = 'Most of this is not stated by the cited source; cite pages that state it.';
/** The review every hand-converted part records. */
const REVIEW = { reviewedBy: 'ryan', reviewedAt: '2026-09-27' };

function franceTree() {
  const contentDir = tempContentTree();
  const review = { contentDir, by: 'Tester', date: RUN_DATE, notes: NOTES };
  const read = () => readCountryFile(contentDir, 'france')!;
  return { contentDir, review, read };
}

const summaryContext = (contentDir: string, file: CountryFile) => ({
  files: parsedCountryFiles(contentDir),
  issues: [],
  pending: [],
  urlStatuses: new Map(),
  claims: readClaims(defaultClaimsDir(contentDir), file.country),
});

const request = (scope?: 'overview') => ({
  notes: NOTES,
  requestedBy: 'Tester',
  requestedAt: RUN_DATE,
  ...(scope ? { scope } : {}),
  reopened: REVIEW,
});

/** A story's provenance once reopened: a draft that names no reviewer outside its request. */
const reopenedStory = {
  generatedBy: 'human',
  generatedAt: '2026-09-26',
  status: 'draft',
  revision: request(),
};

describe('reopening reviewed content', () => {
  it('turns a reviewed story into a draft sent back, with the review it undid on record', () => {
    const { contentDir, review, read } = franceTree();
    const before = read();
    const result = reopen({ ...review, country: 'FRA', storyId: 'overseas' });
    expect(result).toMatchObject({
      countryId: 'FRA',
      overview: false,
      storyIds: ['overseas'],
      reopened: [{ label: 'FRA/overseas', ...REVIEW }],
      skipped: [],
      agentCommand: 'npm run content:agent -- start FRA --revisions',
    });

    const after = read();
    const overseas = after.stories.find((story) => story.id === 'overseas')!;
    expect(overseas.provenance).toEqual(reopenedStory);
    expect(CountryFile.safeParse(after).success).toBe(true);
    // Nothing else changed: the overview and the other stories are still reviewed as they were.
    expect(after.country).toEqual(before.country);
    expect(after.stories.filter((story) => story.id !== 'overseas')).toEqual(
      before.stories.filter((story) => story.id !== 'overseas'),
    );
    expect({ ...overseas, provenance: undefined }).toEqual({
      ...before.stories.find((story) => story.id === 'overseas'),
      provenance: undefined,
    });

    // Review shows it as reopened, and approval waits for the redraft.
    const row = listing([{ file: 'france.json', data: after }])[0];
    expect(row).toMatchObject({ storyRevisions: 1, reopenedStories: 1, overviewReopened: false });
    expect(sentBackText(row)).toBe('1 story (1 reopened)');
    const shown = countrySummary(after, summaryContext(contentDir, after), 'overseas');
    expect(shown).toContain(
      `FRA/overseas, Geography & history, draft (reopened), generated by human on 2026-09-26\n  REVISION REQUESTED by Tester on ${RUN_DATE}: ${NOTES}\n  REOPENED after review by ryan on 2026-09-27; a draft until approved again`,
    );
    expect(() => approve({ ...review, country: 'FRA', storyId: 'overseas' })).toThrow(
      'Waiting for a revision: FRA/overseas.',
    );

    // Production leaves the reopened story out, and every link to it.
    const production = createContentStore(readContentTree(contentDir), { includeDrafts: false });
    expect(production.getStory('FRA', 'overseas')).toBeUndefined();
    expect(production.getStory('FRA', 'paris')).toBeDefined();
    expect(
      production
        .listStories()
        .flatMap((story) => story.next)
        .some((ref) => ref.countryId === 'FRA' && ref.storyId === 'overseas'),
    ).toBe(false);

    const report = reopenReport(result);
    expect(report).toContain('  FRA/overseas (reviewed by ryan on 2026-09-27)');
    expect(report).toContain('Production builds leave drafts out until they are approved again.');
    expect(report).toContain(
      '1. Redraft in a Claude Code content-drafter subagent with npm run content:agent -- start FRA --revisions, or through the API with npm run content:generate -- --revisions.',
    );
    expect(report).toContain('npm run content:paraphrase -- FRA');
    expect(report).toContain('4. Read it with npm run content:review -- show FRA, then approve.');
  });

  it('reopens a reviewed overview alone and keeps every story', () => {
    const { contentDir, review, read } = franceTree();
    const before = read();
    const result = reopen({ ...review, country: 'france', overview: true });
    expect(result).toMatchObject({
      overview: true,
      storyIds: [],
      reopened: [{ label: 'FRA overview' }],
    });
    const after = read();
    expect(after.country.provenance).toEqual({
      generatedBy: 'human',
      generatedAt: '2026-09-26',
      status: 'draft',
      revision: request('overview'),
    });
    expect(after.stories).toEqual(before.stories);

    const row = listing([{ file: 'france.json', data: after }])[0];
    expect(sentBackText(row)).toBe('overview (reopened)');
    expect(countrySummary(after, summaryContext(contentDir, after))).toContain(
      `  draft (reopened), generated by human on 2026-09-26\n  REVISION REQUESTED for the overview alone by Tester on ${RUN_DATE}: ${NOTES}\n  REOPENED after review by ryan on 2026-09-27`,
    );
    const report = reopenReport(result);
    expect(report).toContain('while the overview is a draft they leave out the whole of FRA');
    expect(report).not.toContain('content:paraphrase');
    expect(report).toContain('3. Read it with npm run content:review -- show FRA, then approve.');
  });

  it('reopens a whole country as the overview and every story, never as one file', () => {
    const { contentDir, review, read } = franceTree();
    const before = read();
    const result = reopen({ ...review, country: 'FRA', all: true });
    expect(result.reopened.map((part) => part.label)).toEqual([
      'FRA overview',
      'FRA/paris',
      'FRA/europe',
      'FRA/overseas',
    ]);
    const after = read();
    expect(after.country.provenance.revision).toEqual(request('overview'));
    for (const story of after.stories) expect(story.provenance).toEqual(reopenedStory);
    // The story IDs and their order stay as they were.
    expect(after.stories.map((story) => story.id)).toEqual(before.stories.map((story) => story.id));
    expect(sentBackText(listing([{ file: 'france.json', data: after }])[0])).toBe(
      'overview (reopened), 3 stories (3 reopened)',
    );

    // Nothing in the file is reviewed now, but it still cannot go back as one file.
    expect(() => requestRevision({ ...review, country: 'FRA' })).toThrow(
      'A country redraft replaces the whole file and could renumber or drop stories, and FRA, FRA/paris, FRA/europe, FRA/overseas was reviewed and is reopened.',
    );
    expect(replaceConflict(after, { regenerate: true, force: false })).toBe('reviewed');
    expect(replaceConflict(after, { regenerate: false, force: true })).toBeUndefined();

    // New notes on a reopened part keep the review it undid.
    requestRevision({ ...review, country: 'FRA', storyId: 'paris', notes: 'Shorter.' });
    requestRevision({ ...review, country: 'FRA', overview: true, notes: 'Name the regions.' });
    const renoted = read();
    expect(renoted.stories[0].provenance.revision).toEqual({ ...request(), notes: 'Shorter.' });
    expect(renoted.country.provenance.revision).toEqual({
      ...request('overview'),
      notes: 'Name the regions.',
    });

    // Production leaves out the whole country while its overview is a draft.
    const production = createContentStore(readContentTree(contentDir), { includeDrafts: false });
    expect(production.getCountry('FRA')).toBeUndefined();
    expect(production.getCountry('SGP')).toBeDefined();
  });

  it('reopens with --all only what is reviewed, and leaves drafts as they are', () => {
    const { review, read } = franceTree();
    reopen({ ...review, country: 'FRA', storyId: 'paris' });
    const result = reopen({ ...review, country: 'FRA', all: true, notes: 'Everything else.' });
    expect(result.reopened.map((part) => part.label)).toEqual([
      'FRA overview',
      'FRA/europe',
      'FRA/overseas',
    ]);
    expect(result.skipped).toEqual(['FRA/paris']);
    expect(reopenReport(result)).toContain('Left as they are, already drafts: FRA/paris');
    expect(read().stories[0].provenance.revision?.notes).toBe(NOTES);
  });

  it('refuses drafts, unknown stories and requests that do not say what to reopen', () => {
    const { contentDir, review, read } = franceTree();
    const before = read();
    expect(() => reopen({ ...review, country: 'FRA', storyId: 'louvre' })).toThrow(
      'FRA has no story "louvre"',
    );
    expect(() => reopen({ ...review, country: 'FRA' })).toThrow(
      'Say what to reopen: a story (reopen FRA <story>), the overview (--overview), or the overview and every reviewed story (--all).',
    );
    expect(() => reopen({ ...review, country: 'FRA', storyId: 'paris', overview: true })).toThrow(
      '--overview reopens the country part alone',
    );
    expect(() => reopen({ ...review, country: 'FRA', storyId: 'paris', all: true })).toThrow(
      '--all reopens the overview and every reviewed story',
    );
    expect(() => reopen({ ...review, country: 'FRA', storyId: 'paris', notes: ' ' })).toThrow(
      'Say why it is reopened',
    );
    expect(read()).toEqual(before);

    // A part reopened once is a draft sent back.
    reopen({ ...review, country: 'FRA', storyId: 'paris' });
    expect(() => reopen({ ...review, country: 'FRA', storyId: 'paris' })).toThrow(
      'FRA/paris is not reviewed: it is a draft already sent back, so there is nothing to reopen.',
    );
    reopen({ ...review, country: 'FRA', overview: true });
    expect(() => reopen({ ...review, country: 'FRA', overview: true })).toThrow(
      'The overview of FRA is not reviewed: it is a draft already sent back',
    );

    // A draft nobody reviewed goes back with revise instead.
    writeCountryFile(
      contentDir,
      assembleCountry(CountryDraft.parse(chileDraft()), {
        countryId: 'CHL',
        slug: 'chile',
        model: 'claude-opus-5-5',
        date: '2026-10-01',
        promptVersion: 'v3',
      }),
    );
    expect(() => reopen({ ...review, country: 'CHL', storyId: 'andes' })).toThrow(
      'CHL/andes is not reviewed: it is a draft, so there is nothing to reopen. Send it back with npm run content:review -- revise CHL andes --notes "..."',
    );
    expect(() => reopen({ ...review, country: 'CHL', all: true })).toThrow(
      'Nothing in CHL is reviewed, so there is nothing to reopen.',
    );
    expect(() => reopen({ ...review, country: 'CHL', all: true })).toThrow(ReviewError);
  });

  it('points revise at reopen for reviewed content', () => {
    const { review } = franceTree();
    expect(() => requestRevision({ ...review, country: 'FRA', storyId: 'paris' })).toThrow(
      'FRA/paris is already reviewed. To redraft it, reopen it with npm run content:review -- reopen FRA paris --notes "..."',
    );
    expect(() => requestRevision({ ...review, country: 'FRA', overview: true })).toThrow(
      'reopen it with npm run content:review -- reopen FRA --overview',
    );
    expect(() => requestRevision({ ...review, country: 'FRA' })).toThrow(
      'reopen reviewed parts with npm run content:review -- reopen FRA --all --notes "..."',
    );
  });

  it('keeps provenance honest: only reviewed content names a reviewer', () => {
    const { read } = franceTree();
    const file = read();
    const draftWithReviewer = structuredClone(file);
    draftWithReviewer.stories[0].provenance.status = 'draft';
    const parsed = CountryFile.safeParse(draftWithReviewer);
    expect(parsed.success).toBe(false);
    expect(JSON.stringify(parsed.error?.issues)).toContain(
      'Only reviewed content records a reviewer',
    );
  });
});

describe('the API revision of a reopened hand-written story', () => {
  it(
    'shows the story as written, keeps its ID and camera, and accepts wording kept from a fetched source',
    () => {
      const { contentDir, review, read } = franceTree();
      reopen({ ...review, country: 'FRA', storyId: 'overseas' });
      const existing = read();
      const overseas = existing.stories.find((story) => story.id === 'overseas')!;
      const setup = storySession(runContext(contentDir), existing, 'overseas');
      const task = setup.task.map((block) => block.text).join('\n');
      // The story as it is written in the file: hand-written provenance, sources without an
      // access date, no paraphrases and no request.
      const { paraphrases, ...withoutParaphrases } = overseas;
      expect(paraphrases).toBeDefined();
      expect(task).toContain(
        JSON.stringify(
          { ...withoutParaphrases, provenance: { ...overseas.provenance, revision: undefined } },
          null,
          2,
        ),
      );
      expect(task).toContain(NOTES);
      expect(task).toContain('"generatedBy": "human"');
      expect(task).not.toMatch(/reviewedBy|accessedAt|"revision"|"paraphrases"|undefined/);

      // A redraft that keeps the wording of the first section and cites a new page for the second.
      const newSource = {
        id: 'insee-overseas',
        title: 'Overseas France',
        publisher: 'INSEE',
        url: 'https://www.insee.fr/en/statistiques/overseas',
      };
      const draft = toDraftStory(overseas);
      draft.sections[1].sourceIds = [newSource.id];
      const submission = setup.submit(
        { story: draft, sources: [...toDraftSources(overseas.sources), newSource] },
        {
          model: 'claude-opus-5-5',
          evidence: new Set(
            [...overseas.sources, newSource].map((source) => normalizeUrl(source.url)),
          ),
        },
      );
      if (!submission.ok) throw new Error(submission.issues.join('\n'));
      const revised = submission.file.stories.find((story) => story.id === 'overseas')!;
      expect(revised.sections.map((section) => section.text)).toEqual(
        overseas.sections.map((section) => section.text),
      );
      expect(revised.scene.camera).toEqual(overseas.scene.camera);
      expect(revised.provenance).toEqual({
        generatedBy: 'claude-opus-5-5',
        generatedAt: RUN_DATE,
        promptVersion: 'v3',
        status: 'draft',
      });
      expect(revised.sources.map((source) => source.accessedAt)).toEqual([RUN_DATE, RUN_DATE]);
      expect(submission.file.stories.map((story: Story) => story.id)).toEqual(
        existing.stories.map((story) => story.id),
      );
    },
    REDRAFT_TIMEOUT_MS,
  );

  it('shows a reopened hand-written overview in the submission shape', () => {
    const { contentDir, review, read } = franceTree();
    reopen({ ...review, country: 'FRA', overview: true });
    const setup = overviewSession(runContext(contentDir), read());
    const task = setup.task.map((block) => block.text).join('\n');
    expect(task).toContain(NOTES);
    expect(task).toContain('"kicker": "A national idea with an international life."');
    expect(task).not.toMatch(/reviewedBy|accessedAt|"revision"|undefined/);
  });
});
