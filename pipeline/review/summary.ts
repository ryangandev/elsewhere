// Readable summaries of drafts for review in the terminal: questions, sections with their
// sources, the map scene by place name, and the validation warnings that concern the file.
import type { CountryFile, SceneSpec, Source, Story } from '../../src/content/schema';
import type { ContentIssue, PendingReference } from '../../src/content/validate';
import { gazetteerPlaces, requireMapCountry } from '../content-tree';
import type { UrlStatus } from '../validate/urls';

export type ReviewContext = {
  /** Every country file in the tree, by country ID, to resolve next questions. */
  files: Map<string, CountryFile>;
  /** Validation issues for this file. */
  issues: ContentIssue[];
  pending: PendingReference[];
  urlStatuses: Map<string, UrlStatus>;
};

let placeNames: Map<string, string> | undefined;
const placeName = (id: string) => {
  placeNames ??= new Map(gazetteerPlaces().map((place) => [place.id, place.name]));
  return placeNames.get(id) ?? `${id} (unknown place)`;
};

const countryName = (id: string, files: Map<string, CountryFile>) =>
  files.get(id)?.country.name ?? requireMapCountry(id).name;

function status(entry: { provenance: Story['provenance'] }): string {
  const { provenance } = entry;
  const parts: string[] = [provenance.status];
  if (provenance.status === 'reviewed')
    parts.push(`by ${provenance.reviewedBy} on ${provenance.reviewedAt}`);
  parts.push(`generated by ${provenance.generatedBy} on ${provenance.generatedAt}`);
  if (provenance.promptVersion) parts.push(`prompts ${provenance.promptVersion}`);
  const line = parts.join(', ');
  return provenance.revision
    ? `${line}\n  REVISION REQUESTED by ${provenance.revision.requestedBy} on ${provenance.revision.requestedAt}: ${provenance.revision.notes}`
    : line;
}

const cite = (ids: string[]) => `[${ids.join(', ')}]`;

function scene(spec: SceneSpec, files: Map<string, CountryFile>): string[] {
  const lines = [`  Focus: ${countryName(spec.focusCountryId, files)}`];
  if (spec.highlights.length) {
    lines.push(
      `  Highlights: ${spec.highlights.map((highlight) => `${countryName(highlight.countryId, files)} (${highlight.role})`).join(', ')}`,
    );
  }
  if (spec.placeIds.length) lines.push(`  Places: ${spec.placeIds.map(placeName).join(', ')}`);
  for (const route of spec.routes) {
    lines.push(`  Route ${route.id} (${route.kind}): ${route.via.map(placeName).join(' -> ')}`);
  }
  if (spec.mapNote) lines.push(`  Map note: ${spec.mapNote}`);
  return lines;
}

function sources(list: Source[], statuses: Map<string, UrlStatus>): string[] {
  return list.map((source) => {
    const urlStatus = statuses.get(source.url);
    const state = urlStatus ? `${urlStatus.state}, ${urlStatus.detail}` : 'not checked';
    return `  [${source.id}] ${source.title}. ${source.publisher}. ${source.url} (read ${source.accessedAt ?? 'unknown'}; ${state})`;
  });
}

/**
 * The phrasings search also matches. They make no claims and their edits do not reset review,
 * but the reviewer reads them: a phrasing that asks something else sends readers to this story.
 */
function paraphrases(story: Story): string[] {
  const entry = story.paraphrases;
  if (!entry) {
    return [`  Search phrasings: none yet (npm run content:paraphrase -- ${story.countryId})`];
  }
  const stale = entry.question === story.question ? '' : `, STALE: written for "${entry.question}"`;
  return [
    `  Search phrasings (${entry.generatedBy} on ${entry.generatedAt}${stale})`,
    ...entry.phrasings.map((phrasing) => `  - ${phrasing}`),
  ];
}

export function storySummary(story: Story, context: ReviewContext): string {
  const lines = [
    `### ${story.question}`,
    `  ${story.countryId}/${story.id}, ${story.category}, ${status(story)}`,
    '',
    `  ${story.summary}`,
    '',
  ];
  for (const section of story.sections) {
    lines.push(`  ${section.title} ${cite(section.sourceIds)}`, `    ${section.text}`, '');
  }
  lines.push(
    `  Takeaway: ${story.takeaway}`,
    '',
    '  Map scene',
    ...scene(story.scene, context.files),
    '',
    ...paraphrases(story),
    '',
  );
  lines.push('  Next questions');
  for (const ref of story.next) {
    const target = context.files
      .get(ref.countryId)
      ?.stories.find((entry) => entry.id === ref.storyId);
    const label = target
      ? `"${target.question}"${target.provenance.status === 'draft' ? ' (draft)' : ''}`
      : context.files.has(ref.countryId)
        ? '(missing story)'
        : '(pending: country not drafted yet)';
    lines.push(
      `  -> ${ref.countryId}/${ref.storyId} ${label}${ref.reason ? `: ${ref.reason}` : ''}`,
    );
  }
  lines.push('', '  Sources', ...sources(story.sources, context.urlStatuses));
  return lines.join('\n');
}

export function countrySummary(
  file: CountryFile,
  context: ReviewContext,
  storyId?: string,
): string {
  const { country } = file;
  const lines: string[] = [];
  const stories = storyId ? file.stories.filter((story) => story.id === storyId) : file.stories;
  if (!storyId) {
    lines.push(
      `# ${country.name}${country.nativeName ? ` (${country.nativeName})` : ''}, ${country.id}, ${country.region}`,
      `  ${status(country)}`,
      '',
      `  ${country.kicker}`,
      '',
      `  ${country.overview.summary} ${cite(country.overview.sourceIds)}`,
      `  ${country.overview.geography}`,
      '',
      '  Why it matters',
      ...country.overview.whyItMatters.map(
        (item) => `  - ${item.title}: ${item.text} ${cite(item.sourceIds)}`,
      ),
      '',
      '  Quick facts',
      ...country.quickFacts.map(
        (fact) =>
          `  - ${fact.label}: ${fact.value}${fact.asOf ? ` (${fact.asOf})` : ''} ${cite(fact.sourceIds)}`,
      ),
      '',
      '  Starter questions',
      ...country.starterStoryIds.map(
        (id) =>
          `  - ${id}: ${file.stories.find((story) => story.id === id)?.question ?? '(missing)'}`,
      ),
      '',
      '  Map scene',
      ...scene(country.scene, context.files),
      '',
      '  Sources',
      ...sources(country.sources, context.urlStatuses),
      '',
    );
  }
  for (const story of stories) lines.push(storySummary(story, context), '');

  const warnings = [
    ...context.issues.map((issue) => `${issue.path}: ${issue.message}`),
    ...context.pending
      .filter(
        (ref) => ref.from.countryId === country.id && (!storyId || ref.from.storyId === storyId),
      )
      .map(
        (ref) =>
          `${ref.from.storyId}: next question ${ref.to.countryId}/${ref.to.storyId} is pending`,
      ),
    ...[...context.urlStatuses]
      .filter(([, urlStatus]) => urlStatus.state !== 'ok')
      .map(([url, urlStatus]) => `${urlStatus.state} source URL: ${url} (${urlStatus.detail})`),
  ];
  lines.push(
    '## Validation',
    ...(warnings.length ? warnings.map((warning) => `  - ${warning}`) : ['  No problems found.']),
  );
  return lines.join('\n');
}

export type DraftListing = {
  countryId: string;
  name: string;
  file: string;
  countryStatus: string;
  draftStories: number;
  reviewedStories: number;
  revisions: number;
  generatedBy: string;
};

export function listing(entries: { file: string; data: CountryFile }[]): DraftListing[] {
  return entries.map(({ file, data }) => ({
    countryId: data.country.id,
    name: data.country.name,
    file,
    countryStatus: data.country.provenance.status,
    draftStories: data.stories.filter((story) => story.provenance.status === 'draft').length,
    reviewedStories: data.stories.filter((story) => story.provenance.status === 'reviewed').length,
    revisions: [data.country, ...data.stories].filter((entry) => entry.provenance.revision).length,
    generatedBy: data.country.provenance.generatedBy,
  }));
}
