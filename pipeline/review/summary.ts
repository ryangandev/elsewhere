// Readable summaries of drafts for review in the terminal: questions, sections with their
// sources and claim check verdicts, the map scene by place name, and the validation warnings
// that concern the file.
import type { CountryFile, SceneSpec, Source, Story } from '../../src/content/schema';
import type { ContentIssue, PendingReference } from '../../src/content/validate';
import {
  claimProblems,
  countVerdicts,
  describeCheck,
  formatCounts,
  unitStatuses,
  type ClaimsFile,
} from '../claims/store';
import {
  overviewUnit,
  quickFactUnit,
  scopeLabel,
  scopeUnits,
  sectionUnit,
  whyItMattersUnit,
  type ClaimScope,
  type ClaimUnit,
} from '../claims/units';
import { gazetteerPlaces, requireMapCountry } from '../content-tree';
import { isReopened } from '../generate/replace';
import type { UrlStatus } from '../validate/urls';
import { PROTOTYPE_QUESTIONS } from '../../src/domain/prototype-urls';
import type { ReopenResult } from './actions';

export type ReviewContext = {
  /** Every country file in the tree, by country ID, to resolve next questions. */
  files: Map<string, CountryFile>;
  /** Validation issues for this file. */
  issues: ContentIssue[];
  pending: PendingReference[];
  urlStatuses: Map<string, UrlStatus>;
  /** Saved claim check results for the country. */
  claims: ClaimsFile;
};

let placeNames: Map<string, string> | undefined;
const placeName = (id: string) => {
  placeNames ??= new Map(gazetteerPlaces().map((place) => [place.id, place.name]));
  return placeNames.get(id) ?? `${id} (unknown place)`;
};

const countryName = (id: string, files: Map<string, CountryFile>) =>
  files.get(id)?.country.name ?? requireMapCountry(id).name;

function status(entry: { provenance: Story['provenance'] }, isCountry = false): string {
  const { provenance } = entry;
  const { revision } = provenance;
  const parts: string[] = [revision?.reopened ? 'draft (reopened)' : provenance.status];
  if (provenance.status === 'reviewed')
    parts.push(`by ${provenance.reviewedBy} on ${provenance.reviewedAt}`);
  parts.push(`generated by ${provenance.generatedBy} on ${provenance.generatedAt}`);
  if (provenance.promptVersion) parts.push(`prompts ${provenance.promptVersion}`);
  const line = parts.join(', ');
  if (!revision) return line;
  const scope = isCountry
    ? revision.scope === 'overview'
      ? ' for the overview alone'
      : ' for the whole country'
    : '';
  const reopened = revision.reopened
    ? `\n  REOPENED after review by ${revision.reopened.reviewedBy} on ${revision.reopened.reviewedAt}; a draft until approved again`
    : '';
  return `${line}\n  REVISION REQUESTED${scope} by ${revision.requestedBy} on ${revision.requestedAt}: ${revision.notes}${reopened}`;
}

const cite = (ids: string[]) => `[${ids.join(', ')}]`;

/** The claim check result for a unit, indented under its text. */
const claimLines = (unit: ClaimUnit, context: ReviewContext) =>
  describeCheck(context.claims.checks[unit.key]).map((line) => `      ${line}`);

function scene(spec: SceneSpec, files: Map<string, CountryFile>): string[] {
  const lines = [`  Focus: ${countryName(spec.focusCountryId, files)}`];
  if (spec.camera) {
    const { lat, lng, altitude } = spec.camera;
    lines.push(`  Camera (set by hand): ${lat}, ${lng}, altitude ${altitude}`);
  }
  if (spec.highlights.length) {
    lines.push(
      `  Highlights: ${spec.highlights.map((highlight) => `${countryName(highlight.countryId, files)} (${highlight.role})`).join(', ')}`,
    );
  }
  if (spec.placeIds.length) lines.push(`  Places: ${spec.placeIds.map(placeName).join(', ')}`);
  for (const route of spec.routes) {
    lines.push(`  Route ${route.id} (${route.kind}): ${route.via.map(placeName).join(' -> ')}`);
  }
  if (spec.mapNote) lines.push(`  Map note: ${spec.mapNote}`);
  return lines;
}

function sources(list: Source[], statuses: Map<string, UrlStatus>): string[] {
  return list.map((source) => {
    const urlStatus = statuses.get(source.url);
    const state = urlStatus ? `${urlStatus.state}, ${urlStatus.detail}` : 'not checked';
    return `  [${source.id}] ${source.title}. ${source.publisher}. ${source.url} (read ${source.accessedAt ?? 'unknown'}; ${state})`;
  });
}

/**
 * The phrasings search also matches. They make no claims and their edits do not reset review,
 * but the reviewer reads them: a phrasing that asks something else sends readers to this story.
 */
function paraphrases(story: Story): string[] {
  const entry = story.paraphrases;
  if (!entry) {
    return [`  Search phrasings: none yet (npm run content:paraphrase -- ${story.countryId})`];
  }
  const stale = entry.question === story.question ? '' : `, STALE: written for "${entry.question}"`;
  return [
    `  Search phrasings (${entry.generatedBy} on ${entry.generatedAt}${stale})`,
    ...entry.phrasings.map((phrasing) => `  - ${phrasing}`),
  ];
}

export function storySummary(story: Story, context: ReviewContext): string {
  const lines = [
    `### ${story.question}`,
    `  ${story.countryId}/${story.id}, ${story.category}, ${status(story)}`,
    '',
    `  ${story.summary}`,
    '',
  ];
  story.sections.forEach((section, index) => {
    lines.push(
      `  ${section.title} ${cite(section.sourceIds)}`,
      `    ${section.text}`,
      ...claimLines(sectionUnit(story, section, index + 1), context),
      '',
    );
  });
  lines.push(
    `  Takeaway: ${story.takeaway}`,
    '',
    '  Map scene',
    ...scene(story.scene, context.files),
    '',
    ...paraphrases(story),
    '',
  );
  lines.push('  Next questions');
  for (const ref of story.next) {
    const target = context.files
      .get(ref.countryId)
      ?.stories.find((entry) => entry.id === ref.storyId);
    const label = target
      ? `"${target.question}"${target.provenance.status === 'draft' ? ' (draft)' : ''}`
      : context.files.has(ref.countryId)
        ? '(missing story)'
        : '(pending: country not drafted yet)';
    lines.push(
      `  -> ${ref.countryId}/${ref.storyId} ${label}${ref.reason ? `: ${ref.reason}` : ''}`,
    );
  }
  lines.push('', '  Sources', ...sources(story.sources, context.urlStatuses));
  return lines.join('\n');
}

export function countrySummary(
  file: CountryFile,
  context: ReviewContext,
  storyId?: string,
): string {
  const { country } = file;
  const lines: string[] = [];
  const stories = storyId ? file.stories.filter((story) => story.id === storyId) : file.stories;
  if (!storyId) {
    lines.push(
      `# ${country.name}${country.nativeName ? ` (${country.nativeName})` : ''}, ${country.id}, ${country.region}`,
      `  ${status(country, true)}`,
      '',
      `  ${country.kicker}`,
      '',
      `  ${country.overview.summary} ${cite(country.overview.sourceIds)}`,
      `  ${country.overview.geography}`,
      ...claimLines(overviewUnit(country), context),
      '',
      '  Why it matters',
      ...country.overview.whyItMatters.flatMap((item, index) => [
        `  - ${item.title}: ${item.text} ${cite(item.sourceIds)}`,
        ...claimLines(whyItMattersUnit(country, item, index + 1), context),
      ]),
      '',
      '  Quick facts',
      ...country.quickFacts.flatMap((fact, index) => [
        `  - ${fact.label}: ${fact.value}${fact.asOf ? ` (${fact.asOf})` : ''} ${cite(fact.sourceIds)}`,
        ...claimLines(quickFactUnit(country, fact, index + 1), context),
      ]),
      '',
      '  Starter questions',
      ...country.starterStoryIds.map(
        (id) =>
          `  - ${id}: ${file.stories.find((story) => story.id === id)?.question ?? '(missing)'}`,
      ),
      '',
      '  Map scene',
      ...scene(country.scene, context.files),
      '',
      '  Sources',
      ...sources(country.sources, context.urlStatuses),
      '',
    );
  }
  for (const story of stories) lines.push(storySummary(story, context), '');

  const scopes: ClaimScope[] = [
    ...(storyId ? [] : [{ kind: 'overview' as const }]),
    ...stories.map((story) => ({ kind: 'story' as const, storyId: story.id })),
  ];
  const claimStatuses = scopes.map((scope) => ({
    scope,
    statuses: unitStatuses(scopeUnits(file, scope), context.claims),
  }));
  const needsAttention = claimStatuses.flatMap(({ scope, statuses }) =>
    claimProblems(statuses, scopeLabel(country.id, scope)),
  );
  lines.push(
    '## Claim check',
    `  ${formatCounts(countVerdicts(claimStatuses.flatMap(({ statuses }) => statuses)))}`,
    ...needsAttention.map((problem) => `  - ${problem}`),
    '',
  );

  const warnings = [
    ...context.issues.map((issue) => `${issue.path}: ${issue.message}`),
    ...context.pending
      .filter(
        (ref) => ref.from.countryId === country.id && (!storyId || ref.from.storyId === storyId),
      )
      .map(
        (ref) =>
          `${ref.from.storyId}: next question ${ref.to.countryId}/${ref.to.storyId} is pending`,
      ),
    ...[...context.urlStatuses]
      .filter(([, urlStatus]) => urlStatus.state !== 'ok')
      .map(([url, urlStatus]) => `${urlStatus.state} source URL: ${url} (${urlStatus.detail})`),
  ];
  lines.push(
    '## Validation',
    ...(warnings.length ? warnings.map((warning) => `  - ${warning}`) : ['  No problems found.']),
  );
  return lines.join('\n');
}

export type DraftListing = {
  countryId: string;
  name: string;
  file: string;
  countryStatus: string;
  draftStories: number;
  reviewedStories: number;
  /** What review sent back of the country part: the whole country or the overview alone. */
  countryRevision?: 'whole country' | 'overview';
  /** Stories sent back on their own. */
  storyRevisions: number;
  /** Whether the overview sent back was reviewed and reopened. */
  overviewReopened: boolean;
  /** How many of the stories sent back were reviewed and reopened. */
  reopenedStories: number;
  generatedBy: string;
};

export function listing(entries: { file: string; data: CountryFile }[]): DraftListing[] {
  return entries.map(({ file, data }) => ({
    countryId: data.country.id,
    name: data.country.name,
    file,
    countryStatus: data.country.provenance.status,
    draftStories: data.stories.filter((story) => story.provenance.status === 'draft').length,
    reviewedStories: data.stories.filter((story) => story.provenance.status === 'reviewed').length,
    countryRevision: data.country.provenance.revision
      ? data.country.provenance.revision.scope === 'overview'
        ? 'overview'
        : 'whole country'
      : undefined,
    storyRevisions: data.stories.filter((story) => story.provenance.revision).length,
    overviewReopened: isReopened(data.country.provenance),
    reopenedStories: data.stories.filter((story) => isReopened(story.provenance)).length,
    generatedBy: data.country.provenance.generatedBy,
  }));
}

/**
 * What a listing row says review sent back, marking what was reopened after review:
 * "overview (reopened), 3 stories (3 reopened)". Empty when nothing is sent back.
 */
export function sentBackText(row: DraftListing): string {
  const parts = [
    ...(row.countryRevision
      ? [`${row.countryRevision}${row.overviewReopened ? ' (reopened)' : ''}`]
      : []),
    ...(row.storyRevisions
      ? [
          `${row.storyRevisions} ${row.storyRevisions === 1 ? 'story' : 'stories'}${row.reopenedStories ? ` (${row.reopenedStories} reopened)` : ''}`,
        ]
      : []),
  ];
  return parts.join(', ');
}

/**
 * Told after reopening or approving content in a country the prototype had questions in: the
 * prototype URL redirects are built from what production publishes (src/domain/legacy-redirects.ts),
 * so they change when a review there does. Other countries' reviews never change them.
 */
export function redirectsNote(countryId: string): string[] {
  return PROTOTYPE_QUESTIONS[countryId]
    ? [
        `${countryId} had questions in the prototype, whose old URLs redirect to what production publishes: rebuild the redirects with npm run redirects:build and commit vercel.json (npm test fails while they are out of date).`,
      ]
    : [];
}

/** What `reopen` prints: what it reopened, what that means for production, and the next commands. */
export function reopenReport(result: ReopenResult): string {
  const id = result.countryId;
  const lines = [
    `Reopened in ${result.file}:`,
    ...result.reopened.map(
      (part) => `  ${part.label} (reviewed by ${part.reviewedBy} on ${part.reviewedAt})`,
    ),
    ...(result.skipped.length
      ? [`Left as they are, already drafts: ${result.skipped.join(', ')}`]
      : []),
    `Each is a draft again, with your notes as its revision request and the review it undid on record there.`,
    `Production builds leave drafts out until they are approved again${result.overview ? `, and while the overview is a draft they leave out the whole of ${id}` : ''}. npm run content:check reports a home screen left with fewer than three published questions.`,
    ...redirectsNote(id),
  ];
  const steps = [
    ...(result.wholeCountry
      ? [
          `Review sent back the whole of ${id} earlier, and a whole-country redraft never replaces reopened content. Narrow that request to the overview with npm run content:review -- revise ${id} --overview --notes "...", so everything is redrafted in place.`,
        ]
      : []),
    `Redraft in a Claude Code content-drafter subagent with ${result.agentCommand}, or through the API with npm run content:generate -- --revisions.`,
    `Run npm run content:verify, then check the claims with npm run content:claims-agent -- start ${id} in a claim-checker subagent (or npm run content:claims -- ${id}).`,
    ...(result.storyIds.length
      ? [`Write the redrafted stories' search phrasings with npm run content:paraphrase -- ${id}.`]
      : []),
    `Read it with npm run content:review -- show ${id}, then approve.`,
  ];
  return [...lines, 'Next:', ...steps.map((step, index) => `  ${index + 1}. ${step}`)].join('\n');
}
